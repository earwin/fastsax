// genPredictDoc generates a genxml-shaped document in memory: a <dataset>
// root full of <record> elements with two attributes, one <group> nesting
// level, and genxml's default rates of CDATA/comments/entities. shuffle
// randomizes the field order per record (defeats layout prediction).
func genPredictDoc(target int, shuffle bool, seed int64) []byte {
	fields := []string{
		"id", "name", "location", "population", "elevation", "timezone",
		"country", "admin1", "latitude", "longitude", "feature", "updated",
	}
	words := []string{
		"alpha", "bravo", "charlie", "delta", "echo", "foxtrot", "golf",
		"hotel", "india", "juliett", "kilo", "lima", "mike", "november",
	}
	rng := rand.New(rand.NewSource(seed))
	var sb bytes.Buffer
	sb.Grow(target + 4096)
	sb.WriteString("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<dataset source=\"genxml\">\n")
	rec := 0
	for sb.Len() < target {
		if rng.Float64() < 0.01 {
			sb.WriteString("  <!-- record generated by genxml; batch=\"")
			sb.WriteString(words[rng.Intn(len(words))])
			sb.WriteString("\" -->\n")
		}
		fmt.Fprintf(&sb, "  <record attr0=\"%s > %d\" attr1=\"%s > %d\">\n",
			words[rng.Intn(len(words))], rec, words[rng.Intn(len(words))], rec)
		if shuffle {
			rng.Shuffle(len(fields), func(i, j int) { fields[i], fields[j] = fields[j], fields[i] })
		}
		open := 0
		for i, name := range fields {
			if i > 0 && i%4 == 0 && open < 1 {
				sb.WriteString("    <group>\n")
				open++
			}
			sb.WriteString("    <")
			sb.WriteString(name)
			sb.WriteString(">")
			val := words[rng.Intn(len(words))] + " " + strconv.Itoa(rng.Intn(1_000_000))
			switch {
			case rng.Float64() < 0.02:
				sb.WriteString("<![CDATA[")
				sb.WriteString(val)
				sb.WriteString(" <raw> & ]] bytes]]>")
			case rng.Float64() < 0.05:
				sb.WriteString(val)
				sb.WriteString(" &amp; co &lt;escaped&gt; &#169;")
			default:
				sb.WriteString(val)
			}
			sb.WriteString("</")
			sb.WriteString(name)
			sb.WriteString(">\n")
		}
		for ; open > 0; open-- {
			sb.WriteString("    </group>\n")
		}
		sb.WriteString("  </record>\n")
		rec++
	}
	sb.WriteString("</dataset>\n")
	return sb.Bytes()
}

// cutRecords slices doc into its complete <tag> records (the reference way:
// full scan plus a depth-counting walk).
func cutRecords(tb testing.TB, doc []byte, tag string) [][]byte {
	tb.Helper()
	tape, cut, err := scanChunk(doc, nil)
	if err != nil || cut != len(doc) {
		tb.Fatalf("cutRecords scan: cut=%d/%d err=%v", cut, len(doc), err)
	}
	tagb := []byte(tag)
	var recs [][]byte
	depth, start := 0, 0
	for _, e := range tape {
		b := doc[e.Start:e.End]
		switch e.Kind {
		case KindStart:
			if matchOpenTag(b, tagb) {
				if depth == 0 {
					start = int(e.Start)
				}
				depth++
			}
		case KindSelfClose:
			if depth == 0 && matchOpenTag(b, tagb) {
				recs = append(recs, b)
			}
		case KindEnd:
			if depth > 0 && matchCloseTag(b, tagb) {
				depth--
				if depth == 0 {
					recs = append(recs, doc[start:e.End])
				}
			}
		}
	}
	return recs
}

// --- auto-detection -------------------------------------------------------

func TestDetectTagDocs(t *testing.T) {
	cases := []struct{ name, doc, want string }{
		{"sample", sampleDoc, "record"},
		{"pi and comment before root",
			"<?xml version=\"1.0\"?>\n  <!-- preamble -->\n<root>\n<item>1</item>\n<item>2</item>\n</root>", "item"},
		{"whitespace heavy", "\n\n  <r>\n   <x a=\"1\">t</x>\n   <x>u</x>\n  </r>\n", "x"},
		{"single record in window", `<db><only><f>1</f></only></db>`, "only"},
		{"self-closing repeats", `<db><p/><p/><p/></db>`, "p"},
		{"first repeated wins over singleton", `<db><meta>m</meta><rec>1</rec><rec>2</rec><audit/></db>`, "rec"},
		{"nested same name", `<top><r><r>deep</r></r><r>flat</r></top>`, "r"},
		{"bom", "\xEF\xBB\xBF<db><a>1</a><a>2</a></db>", "a"},
		{"doctype before root", `<!DOCTYPE db [<!ENTITY e "v">]><db><row/><row/></db>`, "row"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			var detected []byte
			var calls int
			cfg := RecordConfig{OnDetect: func(tag []byte) { detected = tag; calls++ }}
			r, err := detectTag(strings.NewReader(c.doc), &cfg)
			if err != nil {
				t.Fatalf("detectTag: %v", err)
			}
			if string(cfg.Tag) != c.want {
				t.Fatalf("detected %q, want %q", cfg.Tag, c.want)
			}
			if calls != 1 || string(detected) != c.want {
				t.Fatalf("OnDetect: calls=%d tag=%q", calls, detected)
			}
			// No data loss: the returned reader must replay the whole doc.
			var replay bytes.Buffer
			if _, err := replay.ReadFrom(r); err != nil {
				t.Fatal(err)
			}
			if replay.String() != c.doc {
				t.Fatalf("re-fed input differs: %d vs %d bytes", replay.Len(), len(c.doc))
			}
		})
	}
}

func TestDetectTagErrors(t *testing.T) {
	cases := []struct{ name, doc, want string }{
		{"empty root only", `<a/>`, "Tag is required"},
		{"ambiguous", `<db><a/><b/></db>`, "Tag is required"},
		{"empty input", ``, "Tag is required"},
		{"text only", `no markup here`, "Tag is required"},
		{"utf16 bom", "\xFE\xFF\x00<", "UTF-16"},
		{"bad markup", `<db><!x></db>`, "unknown markup"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			cfg := RecordConfig{}
			_, err := detectTag(strings.NewReader(c.doc), &cfg)
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Fatalf("got %v, want containing %q", err, c.want)
			}
		})
	}
}

// TestParseRecordsAutoDetect runs the full pipeline with a nil Tag: the
// buffered detection window must be re-fed, so the output matches the
// explicit-Tag reference exactly.
func TestParseRecordsAutoDetect(t *testing.T) {
	tc := recordCorpus()[1] // "many": preamble, attributes, fakes, 137 records
	ref := refParse(t, []byte(tc.doc), tc.tag)
	for _, workers := range []int{1, 4} {
		for _, ordered := range []bool{false, true} {
			// Tiny window: detection sees only the head of the document.
			for _, chunk := range []int{0, 256} {
				label := fmt.Sprintf("w=%d/ordered=%v/chunk=%d", workers, ordered, chunk)
				var detected string
				cfg := RecordConfig{
					Workers: workers, Ordered: ordered, ChunkSize: chunk,
					OnDetect: func(tag []byte) { detected = string(tag) },
				}
				got, _, _, err := collectParallel([]byte(tc.doc), cfg)
				if err != nil {
					t.Fatalf("%s: %v", label, err)
				}
				if detected != tc.tag {
					t.Fatalf("%s: detected %q, want %q", label, detected, tc.tag)
				}
				checkAgainstRef(t, ref, got, label)
			}
		}
	}
}

func TestParseRecordsAutoDetectErraticReader(t *testing.T) {
	tc := recordCorpus()[1]
	ref := refParse(t, []byte(tc.doc), tc.tag)
	cfg := RecordConfig{Workers: 3, ChunkSize: 128, CarryCap: 32}
	got := map[int64]refRec{}
	var mu sync.Mutex
	err := ParseRecords(&erraticReader{data: []byte(tc.doc)}, cfg, func(w int, rec Record) error {
		var evs []tok
		for _, e := range rec.Events {
			evs = append(evs, tok{e.Kind, string(rec.Bytes(e))})
		}
		mu.Lock()
		got[rec.Index] = refRec{data: string(rec.Data), events: evs}
		mu.Unlock()
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	checkAgainstRef(t, ref, got, "autodetect erratic")
}

// --- field-layout predictor -----------------------------------------------

// TestScanRecordByteIdentical is the core predictor guarantee: for any record
// sequence — learned, mislearned, shuffled, adversarial — scanRecord with a
// live predictor produces the exact tape scanChunk produces.
func TestScanRecordByteIdentical(t *testing.T) {
	adversarial := [][]byte{
		[]byte(`<record id="1"><name>n</name></record>`),
		[]byte(`<record id="2"><name>longer value</name></record>`),
		[]byte(`<record><name >spaced</name ></record>`), // prefix of learned "<name>"
		[]byte(`<record><na>shorter</na><me>x</me></record>`),
		[]byte(`<record><blob><![CDATA[fake </record> close]]></blob></record>`),
		[]byte(`<record><!-- <name>commented</name> --><name>real</name></record>`),
		[]byte(`<record attr="</record>" x="1>2"><name>quoted</name></record>`),
		[]byte(`<record><record><name>inner</name></record></record>`),
		[]byte(`<record/>`),
		[]byte(`<record><name>n</name></record>`), // back to the first layout
	}
	fixed := cutRecords(t, genPredictDoc(64<<10, false, 1), "record")
	shuffled := cutRecords(t, genPredictDoc(64<<10, true, 2), "record")

	sets := []struct {
		name string
		recs [][]byte
	}{
		{"adversarial", adversarial},
		{"fixed", fixed},
		{"shuffled", shuffled},
	}
	for _, set := range sets {
		t.Run(set.name, func(t *testing.T) {
			var pr fieldPredictor
			// Two epochs: epoch 1 learns (and decays), epoch 2 exercises the
			// hit path on stable layouts and the off path on unstable ones.
			for epoch := range 2 {
				for i, rec := range set.recs {
					want, wcut, werr := scanChunk(rec, nil)
					got, gcut, gerr := scanRecord(rec, nil, &pr)
					if !slices.Equal(want, got) || wcut != gcut ||
						(werr == nil) != (gerr == nil) {
						t.Fatalf("epoch %d record %d: tape mismatch\n got: %v cut=%d err=%v\nwant: %v cut=%d err=%v",
							epoch, i, got, gcut, gerr, want, wcut, werr)
					}
				}
			}
			if pr.hits == 0 && set.name == "fixed" {
				t.Fatal("fixed layout produced no prediction hits")
			}
		})
	}
}

// TestPredictorDecay checks the credit mechanism: a stable layout keeps the
// predictor on with a high hit rate, a shuffled one drives it off.
func TestPredictorDecay(t *testing.T) {
	fixed := cutRecords(t, genPredictDoc(64<<10, false, 3), "record")
	var pr fieldPredictor
	for range 2 {
		for _, rec := range fixed {
			if _, _, err := scanRecord(rec, nil, &pr); err != nil {
				t.Fatal(err)
			}
		}
	}
	if pr.dead {
		t.Fatalf("predictor died on a fixed layout (hits=%d misses=%d)", pr.hits, pr.misses)
	}
	if pr.hits < pr.misses*4 {
		t.Fatalf("fixed layout hit rate too low: hits=%d misses=%d", pr.hits, pr.misses)
	}

	shuffled := cutRecords(t, genPredictDoc(64<<10, true, 4), "record")
	var ps fieldPredictor
	for _, rec := range shuffled {
		if _, _, err := scanRecord(rec, nil, &ps); err != nil {
			t.Fatal(err)
		}
	}
	if !ps.dead {
		t.Fatalf("predictor survived a shuffled layout (hits=%d misses=%d)", ps.hits, ps.misses)
	}
}

// TestParseRecordsPredictionIdentical compares full ParseRecords output with
// prediction enabled vs the predictDisabled test hook, on fixed and shuffled
// layouts, across worker/ordered modes.
func TestParseRecordsPredictionIdentical(t *testing.T) {
	defer predictDisabled.Store(false)
	docs := []struct {
		name string
		doc  []byte
	}{
		{"fixed", genPredictDoc(192<<10, false, 11)},
		{"shuffled", genPredictDoc(192<<10, true, 12)},
	}
	for _, d := range docs {
		ref := refParse(t, d.doc, "record")
		for _, workers := range []int{1, 4} {
			for _, ordered := range []bool{false, true} {
				for _, disabled := range []bool{false, true} {
					label := fmt.Sprintf("%s/w=%d/ordered=%v/disabled=%v", d.name, workers, ordered, disabled)
					predictDisabled.Store(disabled)
					cfg := RecordConfig{Tag: []byte("record"), Workers: workers, Ordered: ordered}
					got, _, _, err := collectParallel(d.doc, cfg)
					if err != nil {
						t.Fatalf("%s: %v", label, err)
					}
					checkAgainstRef(t, ref, got, label)
				}
			}
		}
	}
}

// --- stats ----------------------------------------------------------------

func TestRecordStats(t *testing.T) {
	doc := genPredictDoc(512<<10, false, 21)

	var st RecordStats
	err := ParseRecords(bytes.NewReader(doc),
		RecordConfig{Tag: []byte("record"), Workers: 4, Stats: &st, PredictLayout: true},
		func(w int, rec Record) error { return nil })
	if err != nil {
		t.Fatal(err)
	}
	if st.Dispatches.Load() == 0 {
		t.Fatal("no dispatches counted")
	}
	if st.EmptyDispatch.Load() > st.Dispatches.Load() {
		t.Fatalf("empty=%d > dispatches=%d", st.EmptyDispatch.Load(), st.Dispatches.Load())
	}
	if st.PredictHits.Load() == 0 {
		t.Fatal("fixed layout produced no predictor hits")
	}
	_ = st.IOBound() // must be callable; the value is workload-dependent

	// Workers == 1 has no queues: dispatch counters stay zero, predictor
	// counters still flow.
	var seq RecordStats
	err = ParseRecords(bytes.NewReader(doc),
		RecordConfig{Tag: []byte("record"), Workers: 1, Stats: &seq, PredictLayout: true},
		func(w int, rec Record) error { return nil })
	if err != nil {
		t.Fatal(err)
	}
	if seq.Dispatches.Load() != 0 {
		t.Fatalf("sequential mode counted %d dispatches", seq.Dispatches.Load())
	}
	if seq.PredictHits.Load() == 0 {
		t.Fatal("sequential mode produced no predictor hits")
	}

	// Shuffled input must record misses (before the predictor turns off).
	var sh RecordStats
	err = ParseRecords(bytes.NewReader(genPredictDoc(256<<10, true, 22)),
		RecordConfig{Tag: []byte("record"), Workers: 2, Stats: &sh, PredictLayout: true},
		func(w int, rec Record) error { return nil })
	if err != nil {
		t.Fatal(err)
	}
	if sh.PredictMisses.Load() == 0 {
		t.Fatal("shuffled layout recorded no predictor misses")
	}
}

// --- no-regression guard and benchmarks -----------------------------------

// TestPredictShuffledNoRegression is the strict no-regression gate: on a fully shuffled
// layout (worst case: learn, miss, decay off) scanRecord must stay within 2%
// of the prediction-disabled path. Interleaved best-of-N minimums de-noise
// the measurement.
func TestPredictShuffledNoRegression(t *testing.T) {
	if testing.Short() {
		t.Skip("timing-sensitive; skipped in -short")
	}
	doc := genPredictDoc(6<<20, true, 99)
	recs := cutRecords(t, doc, "record")
	tape := make([]Event, 0, 512)
	pass := func(pr *fieldPredictor) {
		for _, rec := range recs {
			var err error
			tape, _, err = scanRecord(rec, tape[:0], pr)
			if err != nil {
				t.Fatal(err)
			}
		}
	}
	run := func(predict bool) time.Duration {
		var pr *fieldPredictor
		if predict {
			pr = &fieldPredictor{} // fresh, like a worker at run start
		}
		start := time.Now()
		for range 3 { // pass 1 learns and decays off; 2-3 are steady state
			pass(pr)
		}
		return time.Since(start)
	}
	run(false) // warm caches
	run(true)
	best := [2]time.Duration{1 << 62, 1 << 62}
	for range 9 {
		if d := run(false); d < best[0] {
			best[0] = d
		}
		if d := run(true); d < best[1] {
			best[1] = d
		}
	}
	over := float64(best[1]-best[0]) / float64(best[0])
	t.Logf("shuffled: disabled=%v predicted=%v overhead=%+.2f%%", best[0], best[1], over*100)
	if over > 0.02 {
		t.Fatalf("prediction overhead on shuffled layout %.2f%% exceeds 2%%", over*100)
	}
}

var (
	predictBenchMu   sync.Mutex
	predictBenchDocs = map[bool][]byte{}
)

// predictBenchDoc returns a cached ~30MB genxml-shaped document.
func predictBenchDoc(shuffle bool) []byte {
	predictBenchMu.Lock()
	defer predictBenchMu.Unlock()
	d, ok := predictBenchDocs[shuffle]
	if !ok {
		d = genPredictDoc(30<<20, shuffle, 1234)
		predictBenchDocs[shuffle] = d
	}
	return d
}

// BenchmarkPredictScanRecord isolates stage 2: one goroutine subparsing the
// pre-cut records of a 30MB document, with and without the layout predictor.
func BenchmarkPredictScanRecord(b *testing.B) {
	for _, layout := range []struct {
		name    string
		shuffle bool
	}{{"fixed", false}, {"shuffled", true}} {
		doc := predictBenchDoc(layout.shuffle)
		recs := cutRecords(b, doc, "record")
		var total int64
		for _, r := range recs {
			total += int64(len(r))
		}
		for _, mode := range []struct {
			name    string
			predict bool
		}{{"predict", true}, {"off", false}} {
			b.Run(layout.name+"/"+mode.name, func(b *testing.B) {
				var prs fieldPredictor
				var pr *fieldPredictor
				if mode.predict {
					pr = &prs
				}
				tape := make([]Event, 0, 512)
				b.SetBytes(total)
				b.ReportAllocs()
				for b.Loop() {
					for _, rec := range recs {
						var err error
						tape, _, err = scanRecord(rec, tape[:0], pr)
						if err != nil {
							b.Fatal(err)
						}
					}
				}
			})
		}
	}
}

// BenchmarkPredictParseRecords is the end-to-end view: full ParseRecords over
// the same 30MB documents at GOMAXPROCS workers, prediction on vs the
// predictDisabled hook. Stage 1 bounds the pipeline, so deltas here are
// smaller than in BenchmarkPredictScanRecord.
func BenchmarkPredictParseRecords(b *testing.B) {
	defer predictDisabled.Store(false)
	for _, layout := range []struct {
		name    string
		shuffle bool
	}{{"fixed", false}, {"shuffled", true}} {
		doc := predictBenchDoc(layout.shuffle)
		for _, mode := range []struct {
			name    string
			predict bool
		}{{"predict", true}, {"off", false}} {
			b.Run(layout.name+"/"+mode.name, func(b *testing.B) {
				predictDisabled.Store(!mode.predict)
				cfg := RecordConfig{Tag: []byte("record"), Workers: runtime.GOMAXPROCS(0), PredictLayout: mode.predict}
				var events int64
				handle := func(w int, rec Record) error {
					events += int64(len(rec.Events)) // benign race across workers; keeps the tape alive
					return nil
				}
				b.SetBytes(int64(len(doc)))
				b.ReportAllocs()
				for b.Loop() {
					if err := ParseRecords(bytes.NewReader(doc), cfg, handle); err != nil {
						b.Fatal(err)
					}
				}
				_ = events
			})
		}
	}
}
