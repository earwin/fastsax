// Command genxml generates realistic nested-record XML for benchmarks and tests.
//
// The layout mimics geodata dumps (the workload gosax's bench was written for):
// a root element containing many <record> elements, each with a fixed or
// shuffled sequence of child fields, optional attributes, and configurable
// rates of CDATA sections, comments and character entities.
//
// Usage:
//
//	genxml -size 100MB -out out.xml
//	genxml -size 500MB -shuffle -cdata 0.05 -comments 0.02 -entities 0.1 -out big.xml
package main

import (
	"bufio"
	"flag"
	"fmt"
	"math/rand"
	"os"
	"strconv"
	"strings"
)

var fieldNames = []string{
	"id", "name", "location", "population", "elevation", "timezone",
	"country", "admin1", "latitude", "longitude", "feature", "updated",
}

var locations = []string{
	"Africa/Abidjan", "Africa/Accra", "Europe/Moscow", "Asia/Tokyo",
	"America/New_York", "Africa/Cairo", "Europe/Berlin", "Asia/Shanghai",
	"Africa/Lagos", "Australia/Sydney", "America/Sao_Paulo", "Africa/Nairobi",
}

var words = []string{
	"alpha", "bravo", "charlie", "delta", "echo", "foxtrot", "golf",
	"hotel", "india", "juliett", "kilo", "lima", "mike", "november",
}

func parseSize(s string) (int64, error) {
	s = strings.ToUpper(strings.TrimSpace(s))
	mult := int64(1)
	switch {
	case strings.HasSuffix(s, "GB"):
		mult, s = 1<<30, strings.TrimSuffix(s, "GB")
	case strings.HasSuffix(s, "MB"):
		mult, s = 1<<20, strings.TrimSuffix(s, "MB")
	case strings.HasSuffix(s, "KB"):
		mult, s = 1<<10, strings.TrimSuffix(s, "KB")
	}
	n, err := strconv.ParseInt(s, 10, 64)
	return n * mult, err
}

func main() {
	size := flag.String("size", "100MB", "approximate output size (e.g. 64KB, 100MB, 1GB)")
	out := flag.String("out", "out.xml", "output file")
	tag := flag.String("tag", "record", "record element name")
	depth := flag.Int("depth", 1, "extra nesting depth inside each record (nested groups)")
	attrs := flag.Int("attrs", 2, "attributes per record element")
	fieldAttrs := flag.Int("fieldattrs", 0, "attributes per field element (attribute-dense shapes)")
	nFields := flag.Int("fields", len(fieldNames), "child fields per record (max 12)")
	attrValueLen := flag.String("attrvaluelen", "", "attr value length range lo-hi (e.g. 20-60); empty = legacy short values")
	cdata := flag.Float64("cdata", 0.02, "fraction of fields emitted as CDATA")
	comments := flag.Float64("comments", 0.01, "fraction of records preceded by a comment")
	entities := flag.Float64("entities", 0.05, "fraction of text values containing entities")
	shuffle := flag.Bool("shuffle", false, "shuffle field order per record (defeats layout prediction)")
	seed := flag.Int64("seed", 42, "PRNG seed")
	flag.Parse()

	target, err := parseSize(*size)
	if err != nil {
		fmt.Fprintln(os.Stderr, "bad -size:", err)
		os.Exit(2)
	}
	f, err := os.Create(*out)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	w := bufio.NewWriterSize(f, 1<<20)
	rng := rand.New(rand.NewSource(*seed))

	written := int64(0)
	count := func(s string) {
		w.WriteString(s)
		written += int64(len(s))
	}

	var avLo, avHi int
	if *attrValueLen != "" {
		if _, err := fmt.Sscanf(*attrValueLen, "%d-%d", &avLo, &avHi); err != nil || avLo < 1 || avHi < avLo {
			fmt.Fprintln(os.Stderr, "bad -attrvaluelen (want lo-hi):", *attrValueLen)
			os.Exit(2)
		}
	}
	// emitAttrs writes n attributes. With -attrvaluelen set, values are
	// word-filled to a random length in [lo,hi]; ~25% contain a raw '>' and
	// ~25% an apostrophe (legal inside double-quoted values, and exactly the
	// bytes that defeat naive tag-end scans).
	emitAttrs := func(sb *strings.Builder, n int, rec int) {
		for a := 0; a < n; a++ {
			if avHi == 0 {
				fmt.Fprintf(sb, " attr%d=\"%s > %d\"", a, words[rng.Intn(len(words))], rec)
				continue
			}
			want := avLo + rng.Intn(avHi-avLo+1)
			fmt.Fprintf(sb, " attr%d=\"", a)
			ln := 0
			switch rng.Intn(4) {
			case 0:
				sb.WriteString("x > y ")
				ln += 6
			case 1:
				sb.WriteString("it's ")
				ln += 5
			}
			for ln < want {
				w := words[rng.Intn(len(words))]
				if ln > 0 {
					sb.WriteByte(' ')
					ln++
				}
				sb.WriteString(w)
				ln += len(w)
			}
			sb.WriteByte('"')
		}
	}

	count("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<dataset source=\"genxml\">\n")

	if *nFields < 1 || *nFields > len(fieldNames) {
		fmt.Fprintln(os.Stderr, "bad -fields: want 1..12")
		os.Exit(2)
	}
	fields := make([]string, *nFields)
	copy(fields, fieldNames[:*nFields])
	var sb strings.Builder
	rec := 0
	for written < target {
		sb.Reset()
		if rng.Float64() < *comments {
			sb.WriteString("  <!-- record generated by genxml; batch=\"")
			sb.WriteString(words[rng.Intn(len(words))])
			sb.WriteString("\" -->\n")
		}
		sb.WriteString("  <")
		sb.WriteString(*tag)
		emitAttrs(&sb, *attrs, rec)
		sb.WriteString(">\n")

		if *shuffle {
			rng.Shuffle(len(fields), func(i, j int) { fields[i], fields[j] = fields[j], fields[i] })
		}
		open := 0
		for i, name := range fields {
			if *depth > 0 && i > 0 && i%4 == 0 && open < *depth {
				sb.WriteString("    <group>\n")
				open++
			}
			sb.WriteString("    <")
			sb.WriteString(name)
			emitAttrs(&sb, *fieldAttrs, rec)
			sb.WriteString(">")
			val := fieldValue(rng, name, rec)
			switch {
			case rng.Float64() < *cdata:
				sb.WriteString("<![CDATA[")
				sb.WriteString(val)
				sb.WriteString(" <raw> & ]] bytes]]>")
			case rng.Float64() < *entities:
				sb.WriteString(val)
				sb.WriteString(" &amp; co &lt;escaped&gt; &#169;")
			default:
				sb.WriteString(val)
			}
			sb.WriteString("</")
			sb.WriteString(name)
			sb.WriteString(">\n")
		}
		for ; open > 0; open-- {
			sb.WriteString("    </group>\n")
		}
		sb.WriteString("  </")
		sb.WriteString(*tag)
		sb.WriteString(">\n")
		count(sb.String())
		rec++
	}
	count("</dataset>\n")

	if err := w.Flush(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := f.Close(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s: %d records, %d bytes\n", *out, rec, written)
}

func fieldValue(rng *rand.Rand, name string, rec int) string {
	switch name {
	case "id":
		return strconv.Itoa(rec)
	case "location", "timezone":
		return locations[rng.Intn(len(locations))]
	case "population", "elevation":
		return strconv.Itoa(rng.Intn(1_000_000))
	case "latitude", "longitude":
		return strconv.FormatFloat(rng.Float64()*180-90, 'f', 5, 64)
	default:
		n := 1 + rng.Intn(4)
		parts := make([]string, n)
		for i := range parts {
			parts[i] = words[rng.Intn(len(words))]
		}
		return strings.Join(parts, " ")
	}
}
